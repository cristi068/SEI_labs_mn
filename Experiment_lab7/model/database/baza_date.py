import psycopg
from psycopg.rows import dict_row
from model.database.configurare_db import ConfigurareDB


class BazaDate:
    """Conexiune PostgreSQL prin psycopg 3 si schema aplicatiei."""

    def __init__(self, configurare=None):
        parametri = configurare if configurare is not None else ConfigurareDB().citeste()
        self.conexiune = psycopg.connect(**parametri, autocommit=True, row_factory=dict_row,
                                        options='-c search_path=public')
        try:
            self._creeaza_schema()
        except Exception:
            self.inchide()
            raise

    def _creeaza_schema(self):
        with self.conexiune.transaction():
            self.conexiune.execute('''CREATE TABLE IF NOT EXISTS aeronave (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                tip TEXT NOT NULL CHECK(tip IN ('Avion', 'Elicopter', 'Drona')),
                model TEXT NOT NULL CHECK(length(trim(model)) > 0),
                viteza DOUBLE PRECISION NOT NULL CHECK(viteza > 0 AND viteza < 'Infinity'::float8),
                autonomie DOUBLE PRECISION NOT NULL CHECK(autonomie > 0 AND autonomie < 'Infinity'::float8),
                nr_pasageri INTEGER CHECK(nr_pasageri >= 0),
                nr_motoare INTEGER CHECK(nr_motoare > 0), altitudine_maxima DOUBLE PRECISION,
                nr_rotori INTEGER CHECK(nr_rotori > 0), tip_motor TEXT, capacitate_cargo DOUBLE PRECISION,
                greutate DOUBLE PRECISION, timp_zbor DOUBLE PRECISION, tip_camera TEXT,
                imagine TEXT NOT NULL, referinta_imagine TEXT NOT NULL)''')
            self.conexiune.execute('CREATE TABLE IF NOT EXISTS configurare (cheie TEXT PRIMARY KEY, valoare TEXT NOT NULL)')
            # Cheie naturala calculata de PostgreSQL: Model 2 precede Model 10.
            self.conexiune.execute("""CREATE OR REPLACE FUNCTION hangar_cheie_model(val TEXT)
                RETURNS TEXT[] LANGUAGE SQL IMMUTABLE STRICT AS $$
                SELECT ARRAY(
                    SELECT CASE WHEN parti[1] ~ '^[0-9]+$'
                        THEN '0' || lpad(length(COALESCE(NULLIF(ltrim(parti[1], '0'), ''), '0'))::text, 10, '0')
                             || COALESCE(NULLIF(ltrim(parti[1], '0'), ''), '0')
                        ELSE '1' || parti[1] END
                    FROM regexp_matches(lower(val), '([0-9]+|[^0-9]+)', 'g')
                         WITH ORDINALITY AS r(parti, ordine)
                    ORDER BY ordine
                ) $$""")

    def inchide(self):
        self.conexiune.close()
